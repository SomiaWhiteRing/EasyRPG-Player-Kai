#!/usr/bin/env python3
"""Generate embedded small pixel fonts. Offline dependencies: fonttools[woff], Pillow.

Input is the unmodified Zfull GB 2026.08.11 release archive;
see README.md for their pinned download locations. No font tools are needed
when building Player: the generated header is checked in.
"""
import argparse
import io
import json
from pathlib import Path
import zipfile

from fontTools.ttLib import TTFont
from PIL import ImageFont


def rasterize(data, size):
    source = TTFont(io.BytesIO(data))
    source.flavor = None
    stream = io.BytesIO()
    source.save(stream)
    font = ImageFont.truetype(io.BytesIO(stream.getvalue()), size)
    baseline = round(source['hhea'].ascent * size / source['head'].unitsPerEm)
    result = {}
    for code in sorted(source.getBestCmap()):
        if code < 32:
            continue
        text = chr(code)
        advance = round(font.getlength(text))
        if not 0 < advance <= size:
            continue
        mask, (left, top) = font.getmask2(text, mode='1', anchor='ls')
        top += baseline
        rows = [0] * 11
        fits = True
        for y in range(mask.size[1]):
            for x in range(mask.size[0]):
                if not mask[y * mask.size[0] + x]:
                    continue
                if not (0 <= left + x < advance and 0 <= top + y < size):
                    fits = False
                    break
                rows[top + y] |= 1 << (left + x)
            if not fits:
                break
        if fits:
            result[code] = (advance, tuple(rows))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('inputs', type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    destination = root / 'src/generated/bitmapfont_small.h'
    archive = zipfile.ZipFile(args.inputs / 'zfull-pixel-font-gb-otf.woff2-v2026.08.11.zip')
    (root / 'resources/smallfonts/SOURCE-NOTICE.md').write_bytes(archive.read('README.md'))
    gbk_han = set()
    for first in range(0x81, 0xff):
        for last in range(0x40, 0xff):
            text = bytes((first, last)).decode('gbk', errors='ignore')
            if len(text) == 1:
                code = ord(text)
                if 0x4e00 <= code <= 0x9fff or 0xf900 <= code <= 0xfaff:
                    gbk_han.add(code)
    report = {}
    with destination.open('w', encoding='utf-8', newline='\n') as out:
        out.write('/* Generated by resources/smallfonts/generate.py. Do not edit.\n'
                  ' * Zfull-GB.2009. Source: Zfull dump 2026.08.11.\n'
                  ' * Font author and license unknown; see resources/smallfonts/SOURCE-NOTICE.md. */\n'
                  '#ifndef EP_BITMAPFONT_SMALL_H\n#define EP_BITMAPFONT_SMALL_H\n'
                  '#include <array>\n#include <cstdint>\n'
                  'namespace SmallPixelFallback {\n'
                  'struct Glyph { char32_t code; uint8_t width; uint16_t rows[11]; };\n')
        for size in (8, 9, 10, 11):
            name = f'Zfull-GB-{size}px.otf.woff2'
            table = rasterize(archive.read(name), size)
            assert ord('?') in table, f'{name}: replacement glyph unavailable'
            out.write(f'constexpr std::array<Glyph, {len(table)}> font_{size} = {{{{\n')
            for code, (width, rows) in sorted(table.items()):
                out.write(f'{{{code},{width},{{' + ','.join(map(str, rows)) + '}},\n')
            out.write('}};\n')
            report[str(size)] = {'characters': len(table),
                                 'CJK_basic': sum(0x4e00 <= c <= 0x9fff for c in table),
                                 'GBK_Han': len(gbk_han.intersection(table)),
                                 'GBK_Han_reference': len(gbk_han)}
        out.write('}\n#endif\n')
    (root / 'resources/smallfonts/coverage.json').write_text(
        json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(report))


if __name__ == '__main__':
    main()
