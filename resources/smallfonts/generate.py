#!/usr/bin/env python3
"""Generate embedded small pixel fonts. Offline dependencies: fonttools[woff], Pillow.

Inputs are Zfull GB, Fusion Pixel and GNU Unifont release files;
see README.md for their pinned download locations. No font tools are needed
when building Player: the generated header is checked in.
"""
import argparse
import io
import json
from pathlib import Path
import zipfile

from fontTools.ttLib import TTFont
from PIL import ImageFont


def rasterize(data, size, codes=None):
    source = TTFont(io.BytesIO(data))
    source.flavor = None
    stream = io.BytesIO()
    source.save(stream)
    font = ImageFont.truetype(io.BytesIO(stream.getvalue()), size)
    baseline = round(source['hhea'].ascent * size / source['head'].unitsPerEm)
    result = {}
    cmap = source.getBestCmap()
    for code in sorted(cmap if codes is None else cmap.keys() & codes):
        if code < 32:
            continue
        text = chr(code)
        advance = round(font.getlength(text))
        if not 0 < advance <= size:
            continue
        mask, (left, top) = font.getmask2(text, mode='1', anchor='ls')
        top += baseline
        rows = [0] * 11
        fits = True
        for y in range(mask.size[1]):
            for x in range(mask.size[0]):
                if not mask[y * mask.size[0] + x]:
                    continue
                if not (0 <= left + x < advance and 0 <= top + y < size):
                    fits = False
                    break
                rows[top + y] |= 1 << (left + x)
            if not fits:
                break
        if fits:
            result[code] = (advance, tuple(rows))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('inputs', type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    destination = root / 'src/generated/bitmapfont_small.h'
    archive = zipfile.ZipFile(args.inputs / 'zfull-pixel-font-gb-otf.woff2-v2026.08.11.zip')
    (root / 'resources/smallfonts/SOURCE-NOTICE.md').write_bytes(archive.read('README.md'))
    gbk_han = set()
    for first in range(0x81, 0xff):
        for last in range(0x40, 0xff):
            text = bytes((first, last)).decode('gbk', errors='ignore')
            if len(text) == 1:
                code = ord(text)
                if 0x4e00 <= code <= 0x9fff or 0xf900 <= code <= 0xfaff:
                    gbk_han.add(code)
    # This is the finite set found in the common-character audit. Do not
    # replace Zfull glyphs or import unrelated Unicode blocks.
    symbols = set(map(ord, 'ẞ‱₩₹₽₿↔↕↩↵⇧∂∆⌘⌥⌫⏎␣♡♥♪♫♬✓✔✕✖✗✘〄〜ゔ・㊗㊙'))
    fusion = {}
    for size in (8, 10):
        path = args.inputs / f'fusion-pixel-font-{size}px-monospaced-otf.woff2-v2026.10.25.zip'
        with zipfile.ZipFile(path) as supplement:
            fusion[size] = rasterize(supplement.read(
                f'fusion-pixel-{size}px-monospaced-zh_hans.otf.woff2'), size, symbols)
            for name in supplement.namelist():
                if name.endswith('.txt'):
                    license_path = root / 'resources/smallfonts/licenses/fusion-pixel' / str(size) / name
                    license_path.parent.mkdir(parents=True, exist_ok=True)
                    license_path.write_bytes(supplement.read(name))
    unifont = (args.inputs / 'unifont-18.0.01.otf').read_bytes()
    tables = {size: rasterize(archive.read(f'Zfull-GB-{size}px.otf.woff2'), size)
              for size in (8, 9, 10, 11)}
    missing = symbols - set().union(*(table.keys() for table in tables.values()))
    report = {}
    with destination.open('w', encoding='utf-8', newline='\n') as out:
        out.write('/* Generated by resources/smallfonts/generate.py. Do not edit.\n'
                  ' * Zfull-GB.2009. Source: Zfull dump 2026.08.11.\n'
                  ' * Zfull license unknown; see resources/smallfonts/SOURCE-NOTICE.md.\n'
                  ' * Additional symbols: Small Pixel Symbols, SIL OFL 1.1; see resources/smallfonts/licenses. */\n'
                  '#ifndef EP_BITMAPFONT_SMALL_H\n#define EP_BITMAPFONT_SMALL_H\n'
                  '#include <array>\n#include <cstdint>\n'
                  'namespace SmallPixelFallback {\n'
                  'struct Glyph { char32_t code; uint8_t width; uint16_t rows[11]; };\n')
        for size in (8, 9, 10, 11):
            name = f'Zfull-GB-{size}px.otf.woff2'
            table = tables[size]
            additions = {}
            generic = rasterize(unifont, size, missing)
            for code in sorted(missing):
                glyph = None
                for native in ((8, 10) if size < 10 else (10, 8)):
                    if code not in fusion[native]:
                        continue
                    width, source_rows = fusion[native][code]
                    target_width = (8 if size == 9 else size) if width == native else max(1, size // 2)
                    rows = [0] * 11
                    for y in range(size):
                        sy = y - (size - native) // 2 if size >= native else y * native // size
                        if not 0 <= sy < native:
                            continue
                        for x in range(target_width):
                            sx = x - (target_width - width) // 2 if target_width >= width else x * width // target_width
                            if 0 <= sx < width and source_rows[sy] & (1 << sx):
                                rows[y] |= 1 << x
                    glyph = (target_width, tuple(rows))
                    additions[f'U+{code:04X}'] = f'Fusion Pixel {native}px'
                    break
                if glyph is None and code in generic:
                    glyph = generic[code]
                    additions[f'U+{code:04X}'] = 'GNU Unifont 18.0.01'
                assert glyph is not None and any(glyph[1]), f'{name}: missing symbol U+{code:04X}'
                table[code] = glyph
            # Zfull omits ordinary spaces from its cmap. Missing whitespace
            # must advance the cursor without becoming a replacement glyph.
            for code, width in ((0x20, size // 2), (0xa0, size // 2),
                                (0x3000, 8 if size == 9 else size)):
                table.setdefault(code, (width, (0,) * 11))
            em = 8 if size == 9 else size
            for code, divisor in ((0x2000, 2), (0x2001, 1), (0x2002, 2), (0x2003, 1),
                                  (0x2004, 3), (0x2005, 4), (0x2006, 6), (0x2009, 5),
                                  (0x200a, 10), (0x202f, 5)):
                table.setdefault(code, (max(1, round(em / divisor)), (0,) * 11))
            table.setdefault(0x2007, (table[ord('0')][0], (0,) * 11))
            table.setdefault(0x2008, (table[ord('.')][0], (0,) * 11))
            table.setdefault(0x205f, (max(1, round(em * 2 / 9)), (0,) * 11))
            for code in (*range(0x200b, 0x2010), *range(0x202a, 0x202f),
                         0x2060, *range(0x2066, 0x206a), 0xfeff, *range(0xfe00, 0xfe10)):
                table[code] = (0, (0,) * 11)
            assert ord('?') in table, f'{name}: replacement glyph unavailable'
            out.write(f'constexpr std::array<Glyph, {len(table)}> font_{size} = {{{{\n')
            for code, (width, rows) in sorted(table.items()):
                out.write(f'{{{code},{width},{{' + ','.join(map(str, rows)) + '}},\n')
            out.write('}};\n')
            report[str(size)] = {'characters': len(table),
                                 'CJK_basic': sum(0x4e00 <= c <= 0x9fff for c in table),
                                 'GBK_Han': len(gbk_han.intersection(table)),
                                 'GBK_Han_reference': len(gbk_han),
                                 'symbol_sources': additions}
        out.write('}\n#endif\n')
    (root / 'resources/smallfonts/coverage.json').write_text(
        json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(report))


if __name__ == '__main__':
    main()
